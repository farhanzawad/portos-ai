import enum
from typing import Optional, Dict, Any
from datetime import datetime
from sqlalchemy import String, Float, Boolean, DateTime, ForeignKey, Enum as SQLEnum, Text, JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.db.base import Base, ProvenanceMixin


class MLTaskTypeEnum(str, enum.Enum):
    REGRESSION = "REGRESSION"
    CLASSIFICATION = "CLASSIFICATION"
    FORECASTING = "FORECASTING"


class ModelArtifact(Base, ProvenanceMixin):
    """Versioned predictive model asset registry."""

    __tablename__ = "model_artifacts"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    model_name: Mapped[str] = mapped_column(String(128), nullable=False, index=True)
    model_version: Mapped[str] = mapped_column(String(32), nullable=False)
    task_type: Mapped[MLTaskTypeEnum] = mapped_column(
        SQLEnum(MLTaskTypeEnum, name="ml_task_type_enum", native_enum=False),
        nullable=False,
    )
    algorithm: Mapped[str] = mapped_column(String(128), nullable=False)
    artifact_path: Mapped[str] = mapped_column(String(512), nullable=False)
    hyperparameters_json: Mapped[Dict[str, Any]] = mapped_column(JSON, default=dict, nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)


class ModelEvaluation(Base, ProvenanceMixin):
    """Quantitative evaluation report and validation benchmarks for a model version."""

    __tablename__ = "model_evaluations"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    model_artifact_id: Mapped[str] = mapped_column(String(64), ForeignKey("model_artifacts.id", ondelete="CASCADE"), nullable=False, index=True)
    evaluation_date: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    dataset_reference: Mapped[str] = mapped_column(String(255), nullable=False)

    # Regression metrics
    mae_hours: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    rmse_hours: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    r2_score: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    # Classification metrics
    precision: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    recall: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    f1_score: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

    metrics_payload_json: Mapped[Dict[str, Any]] = mapped_column(JSON, default=dict, nullable=False)
    synthetic_caveat: Mapped[str] = mapped_column(
        Text,
        default="Synthetic-data demonstration. Not validated for real Chattogram Port operations.",
        nullable=False,
    )


class PredictionRecord(Base, ProvenanceMixin):
    """Historical record of an inference generated by an ML model."""

    __tablename__ = "prediction_records"

    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    model_artifact_id: Mapped[str] = mapped_column(String(64), ForeignKey("model_artifacts.id", ondelete="CASCADE"), nullable=False, index=True)
    vessel_call_id: Mapped[Optional[str]] = mapped_column(String(64), ForeignKey("vessel_calls.id", ondelete="SET NULL"), nullable=True, index=True)
    prediction_timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    input_features_json: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    predicted_value_float: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    predicted_label_str: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    confidence_lower_bound: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    confidence_upper_bound: Mapped[Optional[float]] = mapped_column(Float, nullable=True)

